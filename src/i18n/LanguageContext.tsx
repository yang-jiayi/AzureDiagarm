function replacePhraseAtBoundaries(input: string, english: string, japanese: string): string {
  const startsWithWord = /^[A-Za-z0-9]/.test(english);
  const endsWithWord = /[A-Za-z0-9]$/.test(english);
  let cursor = 0;
  let output = '';

  while (cursor < input.length) {
    const index = input.indexOf(english, cursor);
    if (index === -1) {
      output += input.slice(cursor);
      break;
    }

    const before = index > 0 ? input[index - 1] : '';
    const after = input[index + english.length] ?? '';
    const hasStartBoundary = !startsWithWord || !/[A-Za-z0-9]/.test(before);
    const hasEndBoundary = !endsWithWord || !/[A-Za-z0-9]/.test(after);

    if (hasStartBoundary && hasEndBoundary) {
      output += input.slice(cursor, index) + japanese;
      cursor = index + english.length;
    } else {
      output += input.slice(cursor, index + 1);
      cursor = index + 1;
    }
  }

  return output;
}

function translateJapanese(key: StaticTranslationKey): string {
  const exact = exactJapanese[key];
  if (exact !== undefined) return exact;
  const requestIdMatch = String(key).match(/^(.*) Request ID: (.+)$/s);
  if (requestIdMatch) {
    const translatedMessage = exactJapanese[requestIdMatch[1] as StaticTranslationKey];
    if (translatedMessage !== undefined) {
      return `${translatedMessage} リクエスト ID: ${requestIdMatch[2]}`;
    }
  }
  let result: string = key;
  for (const [english, japanese] of phraseJapanese) {
    result = replacePhraseAtBoundaries(result, english, japanese);
  }
  return result;
}

function interpolate(template: string, params?: TranslationParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, params?: TranslationParams) => string;
  translate: (text: string, params?: TranslationParams) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function getInitialLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'ja') return stored;
  } catch {
    // localStorage can be unavailable in privacy-restricted contexts.
  }
  return navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  }, []);

  const toggleLanguage = useCallback(() => {
    setLanguage(language === 'en' ? 'ja' : 'en');
  }, [language, setLanguage]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback((key: TranslationKey, params?: TranslationParams) => {
    const template = language === 'en'
      ? (key in extraEnglish ? extraEnglish[key as ExtraTranslationKey] : key)
      : (key in extraJapanese ? extraJapanese[key as ExtraTranslationKey] : translateJapanese(key as StaticTranslationKey));
    return interpolate(template, params);
  }, [language]);

  const translate = useCallback((text: string, params?: TranslationParams) => {
    return interpolate(language === 'en' ? text : translateJapanese(text as StaticTranslationKey), params);
  }, [language]);

  const value = useMemo(
    () => ({ language, setLanguage, toggleLanguage, t, translate }),
    [language, setLanguage, toggleLanguage, t, translate],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage must be used within LanguageProvider');
  return value;
}
